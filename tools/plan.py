# ---- schedule: 2 posts per weekday, 10 per week, 7 weeks ----
import datetime as _dt
_HOLIDAYS={_dt.date(2026,11,26),_dt.date(2026,11,27),  # Thanksgiving
           _dt.date(2026,12,24),_dt.date(2026,12,25),
           _dt.date(2026,12,31),_dt.date(2027,1,1)}
def _weekdays(start,count):
    out=[];d=start
    while len(out)<count:
        if d.weekday()<5 and d not in _HOLIDAYS: out.append(d)
        d+=_dt.timedelta(days=1)
    return out

START=_dt.date(2026,11,9)
# interleave clusters so each week carries a mix of topics rather than one theme
_ORDER=[]
_lists={c:list(v) for c,v in CLUSTERS.items()}
while any(_lists.values()):
    for c in CLUSTERS:
        if _lists[c]: _ORDER.append((c,*_lists[c].pop(0)))
DAYS=_weekdays(START,35)
SCHEDULE=[]   # (cluster, slug, title, date, week)
for i,(c,slug,title) in enumerate(_ORDER):
    d=DAYS[i//2]
    SCHEDULE.append((c,slug,title,d.isoformat(),i//10+1))

ORDER={s:i for i,(c,s,t,d,w) in enumerate(SCHEDULE)}
CLUSTER_OF={s:c for c,s,t,d,w in SCHEDULE}
TITLE_OF={s:t for c,s,t,d,w in SCHEDULE}

def links_for(slug):
    """3-4 related posts that are ALREADY LIVE when this one publishes.

    Preference order: earlier posts in the same cluster (most relevant), then the
    three posts that existed before this programme, then earlier posts from other
    clusters. Never links forward, so a published post never points at a 404.
    """
    i=ORDER[slug]; c=CLUSTER_OF[slug]
    earlier=[s for (cc,s,t,d,w) in SCHEDULE[:i]]
    same=[s for s in earlier if CLUSTER_OF[s]==c][::-1]
    other=[s for s in earlier if CLUSTER_OF[s]!=c][::-1]
    seed=CLUSTER_SEED[c]
    pool=same+[seed]+[k for k in EXISTING if k!=seed]+other
    picks=[]
    for s in pool:
        if s!=slug and s not in picks: picks.append(s)
        if len(picks)==4: break
    return [(s,TITLE_OF.get(s) or EXISTING[s]) for s in picks],c
